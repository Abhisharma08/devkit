export const toolPages = toolRoutes.map(([id, slug]) => {
  const guide = guides[id];
  if (!guide) throw new Error(`Missing tool guide: ${id}`);
  return { id, slug, path: toolPath(id), ...guide };
});
export function findToolPage(slug: string) { return toolPages.find(tool => tool.slug === slug); }
